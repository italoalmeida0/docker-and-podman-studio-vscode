export function formatUserMessage(locale: SupportedLocale, message: UserMessage): string {
  const template = (translations[locale] || translations.en)[message.key];
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    message.variables?.[key] === undefined ? match : String(message.variables[key]));
}
