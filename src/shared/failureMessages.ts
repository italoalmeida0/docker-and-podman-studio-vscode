import type { SupportedLocale } from '../config';
import type { FailureKind } from './operationFeedback';
import { formatUserMessage, UserMessage } from './userMessages';

export interface FailurePresentation {
  kind: FailureKind;
  operation?: string;
  operationLocale?: SupportedLocale;
  operationKey?: string;
  resourceRefresh?: boolean;
  settingsSavedLogin?: string;
  completed?: number;
  total?: number;
  direct?: UserMessage;
}

const warningKinds: ReadonlySet<FailureKind> = new Set([
  'timeout', 'missingExecutable', 'missingFile', 'portInUse', 'registryAuth',
  'imageNotFound', 'engineConnection', 'network', 'unsavedChanges',
  'staleResource', 'resourceInUse', 'invalidInput',
]);

export function failureSeverity(failure?: FailurePresentation): 'warning' | 'error' {
  if (failure?.kind === 'diskSpace' || failure?.kind === 'permission') return 'error';
  return failure && (failure.resourceRefresh || warningKinds.has(failure.kind)) ? 'warning' : 'error';
}

