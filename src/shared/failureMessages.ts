export function formatFailureSummary(
  locale: SupportedLocale, failure: FailurePresentation, localizedOperation?: string
): string {
  if (failure.direct) return formatUserMessage(locale, failure.direct);
  const text = translations[locale] || translations.en;
  if (failure.settingsSavedLogin) {
    return text.settingsSavedLogin.replace('{command}', failure.settingsSavedLogin);
  }
  const label = localizedOperation || (failure.operationLocale === locale ? failure.operation : undefined);
  const operation = label ? `${text.failed.replace('{operation}', label)}. ` : '';
  const resource = failure.resourceRefresh ? `${text.resourceRefresh} ` : '';
  const hasProgress = Number.isInteger(failure.completed) && Number.isInteger(failure.total) &&
    (failure.total ?? 0) > 0 && (failure.completed ?? -1) >= 0 &&
    (failure.completed ?? 0) <= (failure.total ?? 0);
  const reason = hasProgress
    ? text.partial.replace('{completed}', String(failure.completed)).replace('{total}', String(failure.total)) +
      (failure.kind === 'timeout' ? ` ${text.timeout}` : '')
    : text[failure.kind] || text.generic;
  return `${operation}${resource}${reason}`;
}
